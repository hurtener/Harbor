// Export writes a portable complete skill package into the verified caller's
// exact session artifact scope. Source authority is always the caller's own
// durable user rung and the exact reachable Agent. No skill, membership,
// configuration revision or proposal record is changed.
func (s *UserSkillImportService) Export(ctx context.Context, req prototypes.AgentConfigUserSkillsExportRequest) (prototypes.AgentConfigUserSkillsExportResponse, error) {
	if err := ctx.Err(); err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, err
	}
	id, q, err := s.resolveIdentityAndReach(ctx, req.AgentID)
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, err
	}
	// Identity on the wire is a compatibility witness, never a selectable
	// source owner (including when an in-process caller bypasses the handler).
	if (req.Identity.Tenant != "" && req.Identity.Tenant != id.TenantID) ||
		(req.Identity.User != "" && req.Identity.User != id.UserID) ||
		(req.Identity.Session != "" && req.Identity.Session != id.SessionID) {
		return prototypes.AgentConfigUserSkillsExportResponse{}, ErrUserSkillImportIdentityRequired
	}
	if err := s.ensureNotRetiredImport(ctx, q, req.AgentID); err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, err
	}
	name := skillpkg.CanonicalName(req.Name)
	if name == "" {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: skill name is empty", ErrIdentityRequired)
	}
	unit, err := s.store.GetInstalledPackage(ctx, q, req.AgentID, name)
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("skill export: read caller package: %w", err)
	}
	if err := skills.ValidateInstalledPackage(unit); err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: %w", ErrUserSkillImportPackageInvalid, err)
	}
	// Export the canonical logical package, not its storage envelope. In
	// particular ScopeUser and AgentID must never enter portable frontmatter.
	logical := unit.Package.Skill
	ingest := importer.PackageIngest{
		Skill: skills.Skill{
			Name: logical.Name, Title: logical.Title, Description: logical.Description,
			Trigger: logical.Trigger, TaskType: logical.TaskType, Tags: logical.Tags,
			Steps: logical.Steps, Preconditions: logical.Preconditions, FailureModes: logical.FailureModes,
			RequiredTools: logical.RequiredTools, RequiredNS: logical.RequiredNS, RequiredTags: logical.RequiredTags,
			Scope: skills.ScopeProject, Origin: skills.OriginPack,
		},
		Package: unit.Package.Normalize(), Hash: unit.PackageHash,
	}
	body, err := s.importer.MaterializePackageBody(ctx, ingest)
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: %w", ErrUserSkillImportPackageInvalid, err)
	}
	exported, err := s.importer.ExportPackage(ctx, ingest, body)
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: %w", ErrUserSkillImportPackageInvalid, err)
	}
	archive, err := exportUserSkillArchive(ctx, exported, unit.Package.Supports)
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: %w", ErrUserSkillImportPackageInvalid, err)
	}
	// The import validator owns every archive/document ceiling. Re-ingestion
	// also proves the generated bytes retain the exact package identity before
	// an artifact is written. Store mode avoids compression-amplification
	// refusals for otherwise valid repetitive support data.
	checked, err := s.importer.ImportPackage(ctx, importer.PackageSource{Archive: archive, PathHint: name + ".zip"})
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: %w", ErrUserSkillImportPackageInvalid, err)
	}
	if checked.Hash != unit.PackageHash {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("%w: exported package hash changed", ErrUserSkillImportHashMismatch)
	}
	ref, err := s.artifacts.PutBytes(ctx, artifactScope(id), archive, artifacts.PutOpts{
		MimeType: "application/zip", Filename: name + ".zip", Namespace: "skill-export",
	})
	if err != nil {
		return prototypes.AgentConfigUserSkillsExportResponse{}, fmt.Errorf("skill export: write caller artifact: %w", err)
	}
	return prototypes.AgentConfigUserSkillsExportResponse{
		Artifact: prototypes.ArtifactRef{
			ID: ref.ID, MimeType: ref.MimeType, SizeBytes: ref.SizeBytes,
			Filename: ref.Filename, SHA256: ref.SHA256, Namespace: ref.Namespace,
			Scope: prototypes.ArtifactScope{Tenant: ref.Scope.TenantID, User: ref.Scope.UserID, Session: ref.Scope.SessionID, Task: ref.Scope.TaskID},
		},
		PackageHash: unit.PackageHash, Name: name, SizeBytes: ref.SizeBytes,
		ProtocolVersion: prototypes.ProtocolVersion,
	}, nil
}

// exportUserSkillArchive wraps the shared logical export and exact support
// bytes in a deterministic archive. Paths and bytes come only from the
// validated installed package; no request string becomes an archive path.
func exportUserSkillArchive(ctx context.Context, exported importer.PackageExport, supports []skills.SupportFile) ([]byte, error) {
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	write := func(name string, data []byte) error {
		if err := ctx.Err(); err != nil {
			return err
		}
		w, err := zw.CreateHeader(&zip.FileHeader{Name: name, Method: zip.Store})
		if err != nil {
			return fmt.Errorf("create archive entry: %w", err)
		}
		if _, err := w.Write(data); err != nil {
			return fmt.Errorf("write archive entry: %w", err)
		}
		return nil
	}
	if err := write(skillpkg.RootSkillFileName, exported.Document); err != nil {
		return nil, err
	}
	// Manifest is normalized by ExportPackage. Select bytes by exact path;
	// the validator already verified their sizes, MIME and digests.
	byPath := make(map[string][]byte, len(supports))
	for _, support := range supports {
		byPath[support.Path] = support.Data
	}
	for _, support := range exported.Manifest {
		data, ok := byPath[support.Path]
		if !ok {
			return nil, fmt.Errorf("%w: exported support missing", skills.ErrInstalledPackageInvalid)
		}
		if err := write(support.Path, data); err != nil {
			return nil, err
		}
	}
	if err := zw.Close(); err != nil {
		return nil, fmt.Errorf("close archive: %w", err)
	}
	return buf.Bytes(), nil
}
